//! The context lexicon: which key words name which kind of secret, which words
//! void a key, which words connect a key to its value in prose, and which words are never a
//! value.

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

/// What a key names. Becomes the placeholder label.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(crate) enum Label {
    Password,
    Pin,
    Token,
    ApiKey,
    Secret,
    PrivateKey,
    Credential,
    RecoveryPhrase,
    ConnectionString,
}

impl Label {
    /// Every label, for the engine's set of placeholder labels.
    pub(crate) const ALL: [Label; 9] = [
        Label::Password,
        Label::Pin,
        Label::Token,
        Label::ApiKey,
        Label::Secret,
        Label::PrivateKey,
        Label::Credential,
        Label::RecoveryPhrase,
        Label::ConnectionString,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Label::Password => "Password",
            Label::Pin => "PIN",
            Label::Token => "Token",
            Label::ApiKey => "API Key",
            Label::Secret => "Secret",
            Label::PrivateKey => "Private Key",
            Label::Credential => "Credential",
            Label::RecoveryPhrase => "Recovery Phrase",
            Label::ConnectionString => "Connection String",
        }
    }

    /// Machine id (`Finding::kind`).
    pub fn kind(self) -> &'static str {
        match self {
            Label::Password => "context_password",
            Label::Pin => "context_pin",
            Label::Token => "context_token",
            Label::ApiKey => "context_api_key",
            Label::Secret => "context_secret",
            Label::PrivateKey => "context_private_key",
            Label::Credential => "context_credential",
            Label::RecoveryPhrase => "context_recovery_phrase",
            Label::ConnectionString => "context_connection_string",
        }
    }
}

/// Strong keys name a secret on their own; weak keys (`key`, `code`, `hash`, …) only count
/// with a random-looking value.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub(crate) enum Strength {
    Weak,
    Strong,
}

/// One lexicon entry: a sequence of lowercase words.
pub(crate) struct Entry {
    pub words: &'static [&'static str],
    pub label: Label,
    pub strength: Strength,
}

const fn s(words: &'static [&'static str], label: Label) -> Entry {
    Entry {
        words,
        label,
        strength: Strength::Strong,
    }
}

const fn w(words: &'static [&'static str]) -> Entry {
    Entry {
        words,
        label: Label::Secret,
        strength: Strength::Weak,
    }
}


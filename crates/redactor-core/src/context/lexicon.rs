/// Hash sets and the first-word index, built once.
struct Index {
    stop: HashSet<&'static str>,
    negative: HashSet<&'static str>,
    single: HashSet<&'static str>,
    /// First word -> entries starting with it, longest first.
    by_first: HashMap<&'static str, Vec<&'static Entry>>,
}

fn index() -> &'static Index {
    static I: OnceLock<Index> = OnceLock::new();
    I.get_or_init(|| {
        let mut by_first: HashMap<&'static str, Vec<&'static Entry>> = HashMap::new();
        for e in ENTRIES {
            by_first.entry(e.words[0]).or_default().push(e);
        }
        for v in by_first.values_mut() {
            v.sort_by_key(|e| std::cmp::Reverse(e.words.len()));
        }
        Index {
            stop: STOPWORDS.iter().copied().collect(),
            negative: NEGATIVE.iter().copied().collect(),
            single: ENTRIES
                .iter()
                .filter(|e| e.words.len() == 1)
                .map(|e| e.words[0])
                .collect(),
            by_first,
        }
    })
}

/// Lexicon entries that start with `first`, longest first.
pub(crate) fn entries_starting(first: &str) -> &'static [&'static Entry] {
    index().by_first.get(first).map_or(&[], |v| v.as_slice())
}

pub(crate) fn is_stopword(lower: &str) -> bool {
    index().stop.contains(lower)
}

pub(crate) fn is_negative(lower: &str) -> bool {
    index().negative.contains(lower)
}

/// True when `lower` is a one-word lexicon entry (or ends with a long strong word).
pub(crate) fn is_lexicon_word(lower: &str) -> bool {
    index().single.contains(lower) || SUFFIX_WORDS.iter().any(|(sw, _)| lower.ends_with(sw))
}

/// Every word the anchor automaton searches for.
pub(crate) fn anchor_words() -> Vec<&'static str> {
    let mut v: Vec<&'static str> = ENTRIES
        .iter()
        .filter(|e| e.words.len() == 1)
        .map(|e| e.words[0])
        .chain(PHRASE_ANCHORS.iter().copied())
        .collect();
    v.sort_unstable();
    v.dedup();
    v
}

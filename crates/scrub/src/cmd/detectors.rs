//! `scrub detectors [--markdown]`: every rule the engine knows.

use redactor_core::{rule_infos, Family, RuleInfo};

use crate::cli::DetectorsArgs;
use crate::out;

pub fn run(args: &DetectorsArgs) {
    let infos = rule_infos();
    out(&if args.markdown {
        markdown(&infos)
    } else {
        plain(&infos)
    });
}

fn plain(infos: &[RuleInfo]) -> String {
    let id_w = infos.iter().map(|i| i.id.len()).max().unwrap_or(2).max(2);
    let mut s = format!(
        "{:<id_w$}  {:<8}  {:<4}  {:<5}  LABEL\n",
        "ID", "FAMILY", "CONF", "ON"
    );
    for i in infos {
        s.push_str(&format!(
            "{:<id_w$}  {:<8}  {:<4.2}  {:<5}  {}\n",
            i.id,
            i.family.as_str(),
            i.confidence,
            plain_default(i),
            i.label
        ));
    }
    s
}

/// PII rules are listed as enabled in the catalog but only run with the PII switch.
fn plain_default(i: &RuleInfo) -> &'static str {
    if i.family == Family::Pii {
        "--pii"
    } else if i.default_enabled {
        "on"
    } else {
        "off"
    }
}

fn markdown_default(i: &RuleInfo) -> &'static str {
    match plain_default(i) {
        "--pii" => "with `--pii`",
        other => other,
    }
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn markdown(infos: &[RuleInfo]) -> String {
    let mut s = String::from("# Detectors\n\n");
    s.push_str(&format!(
        "{} rules, generated by `scrub detectors --markdown`. Confidence is the base value; \
         checksums and context raise or lower it per match. Personal-data rules run with \
         `--pii`; rules marked off run when the `enabled` config key names them.\n",
        infos.len()
    ));
    // Families in order of first appearance.
    let mut order: Vec<&str> = Vec::new();
    for i in infos {
        if !order.contains(&i.family.as_str()) {
            order.push(i.family.as_str());
        }
    }
    for family in order {
        let group: Vec<&RuleInfo> = infos
            .iter()
            .filter(|i| i.family.as_str() == family)
            .collect();
        s.push_str(&format!("\n## {}\n\n", group[0].family.title()));
        s.push_str("| Rule | Label | Matches | Confidence | Default |\n|---|---|---|---|---|\n");
        for i in group {
            s.push_str(&format!(
                "| `{}` | {} | {} | {:.2} | {} |\n",
                i.id,
                cell(i.label),
                cell(i.example_shape),
                i.confidence,
                markdown_default(i)
            ));
        }
    }
    s
}
